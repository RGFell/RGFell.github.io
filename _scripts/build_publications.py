"""Generate the Publications and Reports lists from publications/publications.bib.

Runs automatically before every `quarto render` (see `pre-render` in _quarto.yml).
Formatting is done by Quarto's bundled pandoc citeproc with the APA style
(publications/apa.csl); this script only groups the formatted entries by
BibTeX type and year, newest first, and bolds Rodrigo's name.

Output (git-ignored, never edit by hand):
  publications/_list-publications.md   included by publications.qmd
  publications/_list-reports.md        included by reports.qmd
"""

import html
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUB = ROOT / "publications"
BIB = PUB / "publications.bib"
CSL = PUB / "apa.csl"

# BibTeX type (as mapped by pandoc to CSL) -> (page, section heading, anchor)
SECTIONS = [
    ("article-journal",  "publications", "Journal articles",               "journal"),
    ("manuscript",       "publications", "Preprints",                      "preprints"),
    ("paper-conference", "publications", "Conference papers and abstracts", "conference"),
    ("chapter",          "publications", "Book chapters",                  "chapters"),
    ("thesis",           "publications", "Theses",                         "theses"),
    ("report",           "reports",      "Reports",                        "reports"),
]

# Every published spelling of Rodrigo's name, as APA prints it.
MY_NAME = re.compile(r"G[oó]mez(?:[-\u2010 ]Fell)?, R\.(?: A\.)?")  # Gomez-Fell, Gomez Fell, Gómez, Gomez
# citeproc turns "C41F-1589" (an abstract ID stored in `pages`) into a range "C41F–1589".
# IDs contain letters; real page ranges don't, so only those get their hyphen back.
ABSTRACT_ID = re.compile(r"\b([A-Z]+[A-Z0-9]*)–(\d+)\b")


def pandoc(*args, stdin=""):
    return subprocess.run(["quarto", "pandoc", *args], input=stdin, text=True,
                          capture_output=True, check=True).stdout


def main():
    entries = json.loads(pandoc(str(BIB), "-f", "biblatex", "-t", "csljson"))
    meta = {e["id"]: e for e in entries}

    # Format every entry once with citeproc; split the HTML by entry id.
    doc = f"---\nnocite: '@*'\nbibliography: {BIB.as_posix()}\ncsl: {CSL.as_posix()}\n---\n"
    out = pandoc("-f", "markdown", "-t", "html", "--citeproc", "--wrap=none", stdin=doc)
    formatted = {}
    for m in re.finditer(r'<div id="ref-([^"]+)" class="csl-entry"[^>]*>(.*?)</div>', out, re.S):
        body = MY_NAME.sub(lambda n: f"<strong>{n.group(0)}</strong>", m.group(2).strip())
        body = ABSTRACT_ID.sub(r"\1-\2", body)
        formatted[html.unescape(m.group(1))] = body

    pages = {"publications": [], "reports": []}
    known_types = {s[0] for s in SECTIONS}
    for key, e in meta.items():
        if e.get("type") not in known_types:
            raise SystemExit(f"publications.bib: entry '{key}' has unsupported type {e.get('type')}")

    for csl_type, page, heading, anchor in SECTIONS:
        items = [k for k in formatted if meta[k]["type"] == csl_type]  # citeproc order
        if not items:
            continue
        year = lambda k: (meta[k].get("issued", {}).get("date-parts") or [[0]])[0][0]
        lines = [] if page == "reports" else [f"## {heading} {{#{anchor}}}\n"]
        level = "##" if page == "reports" else "###"
        for y in sorted({year(k) for k in items}, reverse=True):
            lines.append(f"{level} {y or 'Undated'} {{#{anchor}-{y}}}\n")
            lines.append("```{=html}")
            lines.append('<div class="pub-list">')
            for k in items:  # citeproc order (alphabetical) within a year
                if year(k) == y:
                    lines.append(f'<div class="csl-entry" id="ref-{k}">{formatted[k]}</div>')
            lines.append("</div>\n```\n")
        pages[page].append("\n".join(lines))

    for page, blocks in pages.items():
        (PUB / f"_list-{page}.md").write_text(
            "<!-- Generated by _scripts/build_publications.py. Do not edit. -->\n\n"
            + "\n".join(blocks), encoding="utf-8")
    print(f"build_publications: {len(meta)} entries -> publications, reports")


if __name__ == "__main__":
    main()
