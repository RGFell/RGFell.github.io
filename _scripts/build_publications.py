"""Generate the Publications and Reports lists from publications/publications.bib.

Runs automatically before every `quarto render` (see `pre-render` in _quarto.yml).
Formatting is done by Quarto's bundled pandoc citeproc with the APA style
(publications/apa.csl); this script only groups the formatted entries by
BibTeX type and year, newest first, and bolds Rodrigo's name.

It also builds the "Selected publications" cards for the Home page from entries
with `keywords = {featured}`, using the optional custom fields `tag`, `summary`,
`image` and `imagealt` (read straight from the .bib, since pandoc drops them).

Output (git-ignored, never edit by hand):
  publications/_list-publications.md   included by publications.qmd
  publications/_list-reports.md        included by reports.qmd
  publications/_featured.md            included by index.qmd
"""

import html
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUB = ROOT / "publications"
BIB = PUB / "publications.bib"
CSL = PUB / "apa.csl"

# BibTeX type (as mapped by pandoc to CSL) -> (page, section heading, anchor)
SECTIONS = [
    ("article-journal",  "publications", "Journal articles",               "journal"),
    ("manuscript",       "publications", "Preprints",                      "preprints"),
    ("paper-conference", "publications", "Conference papers and abstracts", "conference"),
    ("chapter",          "publications", "Book chapters",                  "chapters"),
    ("thesis",           "publications", "Theses",                         "theses"),
    ("report",           "reports",      "Reports",                        "reports"),
]

# Every published spelling of Rodrigo's name, as APA prints it.
MY_NAME = re.compile(r"G[oó]mez(?:[-\u2010 ]Fell)?, R\.(?: A\.)?")  # Gomez-Fell, Gomez Fell, Gómez, Gomez
# citeproc turns "C41F-1589" (an abstract ID stored in `pages`) into a range "C41F–1589".
# IDs contain letters; real page ranges don't, so only those get their hyphen back.
ABSTRACT_ID = re.compile(r"\b([A-Z]+[A-Z0-9]*)–(\d+)\b")
CARD_FIELDS = ("tag", "summary", "image", "imagealt")


def custom_fields(bib_text):
    """{key: {field: value}} for the one-line card fields pandoc ignores."""
    out = {}
    for m in re.finditer(r"@\w+\{([^,\s]+),(.*?)\n\}", bib_text, re.S):
        fields = dict(re.findall(r"^\s*(%s)\s*=\s*\{(.*)\},?\s*$" % "|".join(CARD_FIELDS), m.group(2), re.M))
        out[m.group(1)] = fields
    return out


def short_authors(e):
    names = []
    for a in e.get("author", []):
        initials = " ".join(p[0] + "." for p in re.split(r"[\s.]+", a.get("given", "")) if p)
        names.append(f"{a.get('non-dropping-particle', '') + ' ' if a.get('non-dropping-particle') else ''}{a['family']}, {initials}")
    text = html.escape(", ".join(names[:-1]) + (", & " if len(names) > 1 else "") + names[-1]) if names else ""
    return MY_NAME.sub(lambda n: f"<strong>{n.group(0)}</strong>", text)


def featured_cards(meta, extra):
    keys = [k for k, e in meta.items() if "featured" in [w.strip() for w in e.get("keyword", "").split(",")]]
    year = lambda k: (meta[k].get("issued", {}).get("date-parts") or [[0]])[0][0]
    keys.sort(key=year, reverse=True)
    cards = []
    for k in keys:
        e, x = meta[k], extra.get(k, {})
        venue = html.escape(e.get("container-title", "") or e.get("publisher", ""))
        url = f"https://doi.org/{e['DOI']}" if e.get("DOI") else e.get("URL", "")
        title = html.escape(e.get("title", ""))
        title_html = f'<a href="{url}">{title}</a>' if url else title
        if x.get("image"):
            media = f'<img src="{html.escape(x["image"])}" alt="{html.escape(x.get("imagealt", ""))}" loading="lazy">'
        else:  # no figure: plain blue block with the journal name (decorative; venue is repeated below)
            media = f'<span class="pub-card-venue" aria-hidden="true">{venue}</span>'
        tag = f'<span class="pub-card-tag">{html.escape(x["tag"])}</span>' if x.get("tag") else ""
        summary = f'<p class="pub-card-summary">{html.escape(x["summary"])}</p>' if x.get("summary") else ""
        cards.append(f'''<article class="pub-card">
<div class="pub-card-media">{media}</div>
<div class="pub-card-body">{tag}
<h3 class="pub-card-title">{title_html}</h3>
{summary}
<p class="pub-card-cite">{short_authors(e)} ({year(k)}). <em>{venue}</em>.</p>
</div>
</article>''')
    return ("<!-- Generated by _scripts/build_publications.py. Do not edit. -->\n\n```{=html}\n"
            '<div class="pub-cards">\n' + "\n".join(cards) + "\n</div>\n```\n"), len(cards)


def pandoc(*args, stdin=""):
    return subprocess.run(["quarto", "pandoc", *args], input=stdin, text=True,
                          capture_output=True, check=True).stdout


def main():
    entries = json.loads(pandoc(str(BIB), "-f", "biblatex", "-t", "csljson"))
    meta = {e["id"]: e for e in entries}

    # Format every entry once with citeproc; split the HTML by entry id.
    doc = f"---\nnocite: '@*'\nbibliography: {BIB.as_posix()}\ncsl: {CSL.as_posix()}\n---\n"
    out = pandoc("-f", "markdown", "-t", "html", "--citeproc", "--wrap=none", stdin=doc)
    formatted = {}
    for m in re.finditer(r'<div id="ref-([^"]+)" class="csl-entry"[^>]*>(.*?)</div>', out, re.S):
        body = MY_NAME.sub(lambda n: f"<strong>{n.group(0)}</strong>", m.group(2).strip())
        body = ABSTRACT_ID.sub(r"\1-\2", body)
        key = html.unescape(m.group(1))
        # APA drops `note` for reports; show it at the end of any @techreport entry.
        note = meta.get(key, {}).get("note", "").strip()
        if meta.get(key, {}).get("type") == "report" and note:
            body += " " + html.escape(note) + ("" if note[-1] in ".!?" else ".")
        formatted[key] = body

    pages = {"publications": [], "reports": []}
    known_types = {s[0] for s in SECTIONS}
    for key, e in meta.items():
        if e.get("type") not in known_types:
            raise SystemExit(f"publications.bib: entry '{key}' has unsupported type {e.get('type')}")

    for csl_type, page, heading, anchor in SECTIONS:
        items = [k for k in formatted if meta[k]["type"] == csl_type]  # citeproc order
        if not items:
            continue
        year = lambda k: (meta[k].get("issued", {}).get("date-parts") or [[0]])[0][0]
        lines = [] if page == "reports" else [f"## {heading} {{#{anchor}}}\n"]
        level = "##" if page == "reports" else "###"
        for y in sorted({year(k) for k in items}, reverse=True):
            lines.append(f"{level} {y or 'Undated'} {{#{anchor}-{y}}}\n")
            lines.append("```{=html}")
            lines.append('<div class="pub-list">')
            for k in items:  # citeproc order (alphabetical) within a year
                if year(k) == y:
                    lines.append(f'<div class="csl-entry" id="ref-{k}">{formatted[k]}</div>')
            lines.append("</div>\n```\n")
        pages[page].append("\n".join(lines))

    for page, blocks in pages.items():
        (PUB / f"_list-{page}.md").write_text(
            "<!-- Generated by _scripts/build_publications.py. Do not edit. -->\n\n"
            + "\n".join(blocks), encoding="utf-8")
    featured, n = featured_cards(meta, custom_fields(BIB.read_text(encoding="utf-8")))
    (PUB / "_featured.md").write_text(featured, encoding="utf-8")
    print(f"build_publications: {len(meta)} entries -> publications, reports; {n} featured")


if __name__ == "__main__":
    main()
